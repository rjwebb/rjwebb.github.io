#!/usr/bin/env node
// Convert markdown posts in thoughts/ to HTML.
//
// Write a post as thoughts/YYYY-MM-DD.md with frontmatter:
//
//     ---
//     title: my post title
//     subtitle: a few words about it (optional)
//     date: 2026-07-20
//     ---
//
//     Post body in markdown...
//
// For more posts on the same day, name them YYYY-MM-DD-2.md,
// YYYY-MM-DD-3.md, ...; the highest number is listed first, as the
// most recently published.
//
// Then run `node build_thoughts.js`. Every .md file in thoughts/ is
// converted to a .html file next to it (existing hand-written .html
// posts without a .md source are never touched), and the Thoughts list
// in index.html is regenerated: grouped by year, then by day, newest
// first, each post shown as "title—subtitle". Titles and subtitles of
// hand-written posts are kept from their current entries in index.html.
// Each page also gets social-sharing metadata (see site_meta.js).
// Requires pandoc.

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const { injectMeta } = require("./site_meta");

const THOUGHTS_DIR = path.join(__dirname, "thoughts");
const INDEX = path.join(__dirname, "index.html");

const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

function ordinal(n) {
  if (n % 100 >= 11 && n % 100 <= 13) return `${n}th`;
  return n + ({ 1: "st", 2: "nd", 3: "rd" }[n % 10] || "th");
}

// "2026-07-20" -> "20th July 2026"
function formatDate(isoDate) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(isoDate);
  if (!m) throw new Error(`invalid date: ${isoDate}`);
  return `${ordinal(Number(m[3]))} ${MONTHS[Number(m[2]) - 1]} ${m[1]}`;
}

function escapeHtml(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function parseFrontmatter(text, filename) {
  const meta = {};
  let body = text;
  const match = /^---\s*\n([\s\S]*?)\n---\s*\n/.exec(text);
  if (match) {
    body = text.slice(match[0].length);
    for (const line of match[1].split("\n")) {
      const i = line.indexOf(":");
      if (i !== -1) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  const stem = path.basename(filename, ".md");
  return {
    title: meta.title || stem,
    subtitle: meta.subtitle || "",
    date: meta.date || stem.slice(0, 10), // filename is YYYY-MM-DD[-N]
    body,
  };
}

// The subtitle is a <div>, not a <p>, so site_meta.js doesn't pick it as
// the page description (that should be the first paragraph of the post).
function template(title, subtitle, date, body) {
  const sub = subtitle ? `\n  <div class="post-subtitle">${subtitle}</div>` : "";
  return `<!DOCTYPE html>
<html>

<head>
  <meta charset="utf-8" />
  <title>${title} | bobwebb.org</title>
  <link rel="stylesheet" type="text/css" href="../style/style.css" />
</head>

<body>
  <a href="../index.html">Back</a>
  <h1>${title}</h1>${sub}
  <em>written ${date}</em>

${body}
</body>

</html>
`;
}

function convert(mdPath) {
  const { title, subtitle, date, body } = parseFrontmatter(
    fs.readFileSync(mdPath, "utf8"),
    mdPath
  );
  const bodyHtml = execFileSync("pandoc", ["-f", "markdown", "-t", "html"], {
    input: body,
    encoding: "utf8",
  })
    .trimEnd()
    .split("\n")
    .map((line) => (line ? "  " + line : ""))
    .join("\n");

  const outPath = mdPath.replace(/\.md$/, ".html");
  const html = template(escapeHtml(title), escapeHtml(subtitle), formatDate(date), bodyHtml);
  fs.writeFileSync(outPath, injectMeta(html, path.relative(__dirname, outPath)));
  return { outPath, title, subtitle, date };
}

// The Thoughts list in index.html is regenerated on every run, grouped by
// year and then by day. It lives between these markers; anything between
// them is overwritten.
const LIST_START = "<!-- thoughts list (generated by build_thoughts.js) -->";
const LIST_END = "<!-- /thoughts list -->";
const POST_NAME = /^(\d{4}-\d{2}-\d{2})(?:-(\d+))?\.html$/;

function collapse(s) {
  return s.replace(/\s+/g, " ").trim();
}

// Titles and subtitles of posts as they currently appear in index.html,
// keyed by filename, as HTML. Hand-written posts have no .md to read
// these from, so the index itself is their source of truth: edit their
// link text (or add a <span class="thoughts-subtitle">) there directly.
function existingEntries(indexHtml) {
  const entries = {};
  const re =
    /<a href="thoughts\/([^"]+)"\s*>([^<]*)<\/a\s*>(?:\s*<span class="thoughts-subtitle">(?:—|&mdash;)([^<]*)<\/span\s*>)?/g;
  let m;
  while ((m = re.exec(indexHtml)) !== null) {
    if (!(m[1] in entries)) entries[m[1]] ={ titleHtml: collapse(m[2]), subtitleHtml: m[3] ? collapse(m[3]) : "" };
  }
  return entries;
}

// Every post in thoughts/, with its title and subtitle (as HTML), date,
// and same-day sequence number (2026-11-23-2.html -> 2, no suffix -> 0).
function collectPosts(indexHtml, mdMeta) {
  const known = existingEntries(indexHtml);
  const posts = [];
  for (const name of fs.readdirSync(THOUGHTS_DIR)) {
    const m = POST_NAME.exec(name);
    if (!m) continue;
    const post = { name, date: m[1], seq: m[2] ? Number(m[2]) : 0 };
    if (mdMeta[name]) {
      post.date = mdMeta[name].date;
      post.titleHtml = escapeHtml(mdMeta[name].title);
      post.subtitleHtml = escapeHtml(mdMeta[name].subtitle);
    } else if (known[name]) {
      Object.assign(post, known[name]);
    } else {
      const html = fs.readFileSync(path.join(THOUGHTS_DIR, name), "utf8");
      const h1 = /<h1[^>]*>([\s\S]*?)<\/h1>/.exec(html);
      post.titleHtml = h1 ? collapse(h1[1]) : name;
      post.subtitleHtml = "";
    }
    posts.push(post);
  }
  // newest day first; within a day, the highest sequence number (the
  // last one published) first
  return posts.sort((a, b) =>
    a.date !== b.date ? (a.date < b.date ? 1 : -1) : b.seq - a.seq
  );
}

// "2026-11-23" -> "November 23rd"
function formatDay(isoDate) {
  const [, month, day] = isoDate.split("-").map(Number);
  return `${MONTHS[month - 1]} ${ordinal(day)}`;
}

function renderList(posts, indent) {
  const lines = [LIST_START];
  let year = null;
  let day = null;
  for (const post of posts) {
    if (post.date.slice(0, 4) !== year) {
      if (day !== null) lines.push("</ul>");
      year = post.date.slice(0, 4);
      day = null;
      lines.push(`<h3 class="thoughts-year">${year}</h3>`);
    }
    if (post.date !== day) {
      if (day !== null) lines.push("</ul>");
      day = post.date;
      lines.push(`<div class="thoughts-day">${formatDay(day)}</div>`);
      lines.push('<ul class="thoughts-posts">');
    }
    const sub = post.subtitleHtml
      ? `<span class="thoughts-subtitle">&mdash;${post.subtitleHtml}</span>`
      : "";
    lines.push(`    <li><a href="thoughts/${post.name}">${post.titleHtml}</a>${sub}</li>`);
  }
  if (day !== null) lines.push("</ul>");
  lines.push(LIST_END);
  return lines.map((l, i) => (i === 0 ? l : indent + l)).join("\n");
}

// Replace the generated block (or, the first time, the plain <ul> under
// the Thoughts heading) with a freshly rendered list.
function updateIndex(indexHtml, mdMeta) {
  let start = indexHtml.indexOf(LIST_START);
  let end;
  if (start !== -1) {
    end = indexHtml.indexOf(LIST_END, start) + LIST_END.length;
  } else {
    const heading = indexHtml.indexOf("<h2>Thoughts</h2>");
    if (heading === -1) return null;
    start = indexHtml.indexOf("<ul>", heading);
    if (start === -1) return null;
    end = indexHtml.indexOf("</ul>", start) + "</ul>".length;
  }
  const lineStart = indexHtml.lastIndexOf("\n", start) + 1;
  const indent = indexHtml.slice(lineStart, start).replace(/\S.*/, "");
  const posts = collectPosts(indexHtml, mdMeta);
  return indexHtml.slice(0, start) + renderList(posts, indent) + indexHtml.slice(end);
}

function main() {
  const mdFiles = fs
    .readdirSync(THOUGHTS_DIR)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => path.join(THOUGHTS_DIR, f));

  const mdMeta = {};
  for (const mdPath of mdFiles) {
    const { outPath, title, subtitle, date } = convert(mdPath);
    const name = path.basename(outPath);
    mdMeta[name] = { title, subtitle, date };
    console.log(`${path.basename(mdPath)} -> ${name}`);
  }

  const indexHtml = fs.readFileSync(INDEX, "utf8");
  const updated = updateIndex(indexHtml, mdMeta);
  if (updated === null) {
    console.log("couldn't find the Thoughts list in index.html");
  } else if (updated !== indexHtml) {
    fs.writeFileSync(INDEX, updated);
    console.log("updated the Thoughts list in index.html");
  }
}

main();
